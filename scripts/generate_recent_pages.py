#!/usr/bin/env python3
"""Generate _data/recent_pages.yml — the N most recently changed pages.

Derives the list from _data/visualizations.yml (the canonical list of
visualization pages, which already excludes index/blog/`todo_design/` pages)
and orders it by each file's last git commit time. Files with uncommitted
changes count as "just changed" (now), so a freshly edited page jumps to the
top before you commit it.

The homepage's "Recently added pages" section reads _data/recent_pages.yml.

Re-run after adding or editing pages:
    python3 scripts/generate_recent_pages.py
"""
import os
import subprocess
import time

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 10


def last_modified(filename):
    # A file with uncommitted changes (modified or staged) counts as "now".
    status = subprocess.run(
        ["git", "status", "--porcelain", "--", filename],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.strip()
    if status:
        return time.time()

    out = subprocess.run(
        ["git", "log", "-1", "--format=%ct", "--", filename],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.strip()
    try:
        return int(out)
    except ValueError:
        return 0  # never committed — push it to the bottom


def main():
    master_path = os.path.join(ROOT, "_data", "visualizations.yml")
    with open(master_path, encoding="utf-8") as fh:
        files = yaml.safe_load(fh)

    # A file listed in the master list but absent on disk (e.g. deleted but
    # still listed) would otherwise rank by its deletion commit — skip it.
    existing = [f for f in files if os.path.exists(os.path.join(ROOT, f))]

    # Stable sort: files with identical timestamps (same commit) keep their
    # order from visualizations.yml, so the output is deterministic.
    ranked = sorted(existing, key=last_modified, reverse=True)[:N]

    out_path = os.path.join(ROOT, "_data", "recent_pages.yml")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/generate_recent_pages.py — do not edit by hand.\n")
        yaml.safe_dump(ranked, fh, allow_unicode=True, sort_keys=False, width=100)

    print(f"Wrote {out_path} (top {len(ranked)} by last change):")
    for f in ranked:
        print("  ", f)


if __name__ == "__main__":
    main()
